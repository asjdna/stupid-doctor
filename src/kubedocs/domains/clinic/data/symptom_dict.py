def normalize_symptom(phrase: str) -> str | None:
    """把口语表达归一化到标准症状名，未命中返回 None。"""
    for std, variants in SYMPTOMS.items():
        if phrase in variants:
            return std
    # 反向：短语中包含某个变体
    for std, variants in SYMPTOMS.items():
        for v in variants:
            if v in phrase:
                return std
    return None


def match_symptom_in_text(text: str) -> list[tuple[str, str]]:
    """从一段话中找出命中的症状（返回 [(标准症状, 命中原词), ...]）。"""
    hits = []
    for std, variants in SYMPTOMS.items():
        for v in variants:
            if v in text:
                hits.append((std, v))
    return hits


