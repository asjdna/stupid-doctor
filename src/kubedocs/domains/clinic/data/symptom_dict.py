def match_symptom_in_text(text: str) -> list[tuple[str, str]]:
    """从一段话中找出命中的症状（返回 [(标准症状, 命中原词), ...]）。

    注意返回的是**口语侧的标准症状**，不等于语料词表里的键——要做分诊打分必须再过一道
    `pack.match_symptoms`（它负责把口语折到语料词表上）。
    """
    hits = []
    for std, variants in SYMPTOMS.items():
        for v in variants:
            if v in text:
                hits.append((std, v))
    return hits
