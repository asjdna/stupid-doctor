"""噪声词典：口头禅、语气词、寒暄、无意义填充词。

用于"抗噪"能力的第一层（词典过滤），实现见
`app/capabilities/extractor/noise_filter.py`。该层的策略是**分档**的：

- `NOISE_WORDS` 多字短语 -> 子串删除（jieba 不会把「也不知道是不是」切成一个整词）。
  删除必须**长词优先**，否则短词会把长词的前缀吃掉（「也不知道」吃掉「也不知道是不是」
  -> 残留「是不是」）。
- `NOISE_WORDS` 单字语气词 -> 只能按 jieba **整词 + 词性**（`PARTICLE_POS`）删，
  不能子串删（子串删会把「是」从「但是」、把「有」从「没有」里删掉）。
- `STOPWORDS` -> 只记录、**不删除**（硬删会破坏语义），且只按整词匹配。

⚠️ **改词表前必读**：`NOISE_WORDS` 与 `app/polarity.py` 的转折/否定词表有交集
（当前是「就是」）。`polarity` 判断否定作用域时逗号**不是**分句边界，所以
「没发烧，就是咳嗽」里「就是」是唯一挡住否定作用域的屏障 —— 删掉它，
患者真实说出的「咳嗽」会被判成否定而**静默丢弃**（实测该结构下 5/7 用例丢症状）。
`noise_filter` 因此对与极性标记精确相等的噪声词做了「永不删除」保护，
并有「删除影响守卫」兜底；新增噪声词时不要绕过这两道保护。
"""

# 口头禅 / 填充词 / 寒暄
NOISE_WORDS = [
    "哎呀", "反正", "那个", "就是", "也不知道", "怎么说呢", "其实",
    "我感觉", "我觉得", "可能吧", "应该吧", "嗯", "啊", "哦", "吧", "呢",
    "换季", "最近", "也不知道是不是", "也没什么", "别的倒没啥", "对了",
    "顺便说一下", "你懂我意思吗", "说不上来", "不知道咋说",
]

# 语气词 / 叹词 / 拟声词（配合 jieba 词性标注使用，用于单字噪声的整词剔除）
PARTICLE_POS = {"y", "e", "o"}   # y=语气词, e=叹词, o=拟声词

# 停用词（**只记录不丢弃**；匹配按整词，不做子串匹配）
STOPWORDS = {"的", "了", "我", "你", "他", "她", "它", "是", "在", "有", "和", "就", "都", "也", "还", "又"}
