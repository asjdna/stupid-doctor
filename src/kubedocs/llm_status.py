"""大模型可用性相关的**唯一文案来源**。

这个项目把判断全部交给大模型，于是"模型在不在"变成了一条架构级状态：**没有判断者就没有结论**。
以前遇到这种情况会走各种兜底（检索结果照给、规则轨照答、保守话术顶替），现在只有两句话：

| 情况 | 文案 | 为什么分开 |
|---|---|---|
| 压根没配密钥 | `NO_LLM_MESSAGE` | 用户/运维要去做的是**配置密钥** |
| 配了但这次调用失败（超时/限流/预算） | `LLM_FAILED_MESSAGE` | 用户要做的只是**重试**；运维要查的是网络/额度 |

**刻意不合并成一句**：把"连了但失败"说成"未连接大模型"，会让运维去翻一个其实配好的密钥，
而真正的原因（超时/限流/预算用尽）没有任何人看见。

两句都放在这里而不是散在各模块：文案是**产品契约**，改了要一起改，不能出现
`/chat` 说"未连接"、`/consult` 说"未配置"这种同一状态两种说法。
"""

from __future__ import annotations

NO_LLM_MESSAGE = "未连接大模型，请连接大模型后重试。"
"""**没有配置大模型密钥**时的唯一回复。

所有"需要判断/作答"的入口（`/consult`、`/chat`、`/ask`、CLI `ask`）在无密钥时都只回这一句：
不做检索兜底、不给保守话术、不进规则轨。检索与运维入口（`/search`、`ingest`、`stats`、
`/healthz`、MCP 工具）**不受影响**——它们不需要大模型。
"""

LLM_FAILED_MESSAGE = "大模型调用失败，请稍后重试。"
"""**配了密钥但这次调用没成功**时的唯一回复（超时/限流/输出不可解析/预算用尽）。

它同样替代了所有"按现有证据给个有限结论"的兜底：那些结论没有经过判断者，
把它们当成结论交付，等于用一个没人负责的内容冒充医学判断。
"""
